/* Debug: table checksums (spec/cg_tables.md section 6)                                  */
/*   h = 0xCBF29CE484222325; for v in elements: h = (h ^ (u64)v) * 0x100000001B3          */
/*   FNV-1a per 64-bit ELEMENT (not per byte); signed elements are sign-extended.        */
/* ===================================================================================== */

#define FNV_OFFSET 0xCBF29CE484222325ULL
#define FNV_PRIME  0x00000100000001B3ULL

static u64 fnv_u64(const u64 *a, i64 n)
{
    u64 h = FNV_OFFSET;
    i64 i;
    for (i = 0; i < n; i++)
        h = (h ^ a[i]) * FNV_PRIME;
    return h;
}

static u64 fnv_i64(const i64 *a, i64 n)
{
    u64 h = FNV_OFFSET;
    i64 i;
    for (i = 0; i < n; i++)
        h = (h ^ (u64)a[i]) * FNV_PRIME;
    return h;
}

static u64 fnv_i32(const i32 *a, i64 n)
{
    u64 h = FNV_OFFSET;
    i64 i;
    for (i = 0; i < n; i++)
        h = (h ^ (u64)(i64)a[i]) * FNV_PRIME;      /* sign-extend first */
    return h;
}

