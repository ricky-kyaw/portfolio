#define IX_RAYS(d, sq)  ((d) * 64 + (sq))
#define R_TABLE_LEN     102400
#define B_TABLE_LEN     5248

/* cg_tables.py:55 deltas, as (dr, df):
 * 0=N(+8) 1=NE(+9) 2=E(+1) 3=NW(+7) | 4=S(-8) 5=SE(-7) 6=W(-1) 7=SW(-9) */
static const i64 DELTA_DR[8] = { 1, 1, 0,  1, -1, -1,  0, -1 };
static const i64 DELTA_DF[8] = { 0, 1, 1, -1,  0,  1, -1, -1 };

/* `0 <= rr < 8 and 0 <= ff < 8` */
static int on_board(i64 rr, i64 ff)
{
    return rr >= 0 && rr < 8 && ff >= 0 && ff < 8;
}

/* cg_tables.py:49 _build_attacks */
static void build_attacks(void)
{
    static const i64 KN_DR[8] = { 2, 1, -1, -2, -2, -1,  1,  2 };
    static const i64 KN_DF[8] = { 1, 2,  2,  1, -1, -2, -2, -1 };
    i64 sq, r, f, rr, ff, dr, df, d, i;
    u64 b;

    for (sq = 0; sq < 64; sq++) {
        r = sq / 8;                 /* divmod(sq, 8), sq >= 0 */
        f = sq % 8;

        b = U0;
        for (i = 0; i < 8; i++) {
            rr = r + KN_DR[i];
            ff = f + KN_DF[i];
            if (on_board(rr, ff))
                b |= U1 << (u64)(rr * 8 + ff);
        }
        KNIGHT_ATT[sq] = b;

        b = U0;
        for (dr = -1; dr <= 1; dr++) {
            for (df = -1; df <= 1; df++) {
                if (dr != 0 || df != 0) {
                    rr = r + dr;
                    ff = f + df;
                    if (on_board(rr, ff))
                        b |= U1 << (u64)(rr * 8 + ff);
                }
            }
        }
        KING_ATT[sq] = b;

        PAWN_ATT[IX_PAWN_ATT(0, sq)] = U0;
        PAWN_ATT[IX_PAWN_ATT(1, sq)] = U0;
        for (df = -1; df <= 1; df += 2) {
            if (f + df >= 0 && f + df < 8) {
                if (r + 1 < 8)
                    PAWN_ATT[IX_PAWN_ATT(0, sq)] |= U1 << (u64)((r + 1) * 8 + f + df);
                if (r - 1 >= 0)
                    PAWN_ATT[IX_PAWN_ATT(1, sq)] |= U1 << (u64)((r - 1) * 8 + f + df);
            }
        }

        for (d = 0; d < 8; d++) {
            dr = DELTA_DR[d];
            df = DELTA_DF[d];
            rr = r + dr;
            ff = f + df;
            b = U0;
            while (on_board(rr, ff)) {
                b |= U1 << (u64)(rr * 8 + ff);
                rr += dr;
                ff += df;
            }
            RAYS[IX_RAYS(d, sq)] = b;
        }
    }
}

/* cg_position.py:75 msb. Only ray_attack below needs it here (position.c has its own copy). */
static i64 msb(u64 b)
{
    b |= b >> (u64)1;
    b |= b >> (u64)2;
    b |= b >> (u64)4;
    b |= b >> (u64)8;
    b |= b >> (u64)16;
    b |= b >> (u64)32;
    return DEBRUIJN_IDX[((b - (b >> U1)) * DEBRUIJN) >> (u64)58];
}

/* cg_position.py:95 ray_attack: the reference the magics were verified against. The engine never
 * calls it; it lives here because the slider tables are rebuilt from it. */
static u64 ray_attack(i64 sq, u64 occ, i64 d)
{
    u64 att = RAYS[IX_RAYS(d, sq)];
    u64 blockers = att & occ;
    if (blockers != U0) {
        if (d < 4)
            att ^= RAYS[IX_RAYS(d, lsb(blockers))];
        else
            att ^= RAYS[IX_RAYS(d, msb(blockers))];
    }
    return att;
}

/* Kernighan count, as cg_position.py:86 popcount (kept local so tables.c needs nothing from
 * position.c at start-up). */
static i64 count_bits(u64 b)
{
    i64 n = 0;
    while (b != U0) {
        b &= b - U1;
        n += 1;
    }
    return n;
}

/* One piece type of magics.npz, rebuilt (spec/cg_tables.md section 2.4, steps 1-4).
 * first_dir is 0 for the rook (directions 0, 2, 4, 6) and 1 for the bishop (1, 3, 5, 7). */
static void build_magic(i64 first_dir, const u64 *magic, u64 *mask, u64 *shift, i64 *off, u64 *table)
{
    i64 sq, r, f, rr, ff, dr, df, d, next_off;
    u64 m, sub, att;

    next_off = 0;
    for (sq = 0; sq < 64; sq++) {
        r = sq / 8;
        f = sq % 8;

        /* 1. relevant-occupancy mask: each ray without its last (edge) square */
        m = U0;
        for (d = first_dir; d < 8; d += 2) {
            dr = DELTA_DR[d];
            df = DELTA_DF[d];
            rr = r + dr;
            ff = f + df;
            while (on_board(rr + dr, ff + df)) {
                m |= U1 << (u64)(rr * 8 + ff);
                rr += dr;
                ff += df;
            }
        }
        mask[sq] = m;

        /* 2. shift, 3. offset: blocks of 1 << popcount(mask), squares in order */
        shift[sq] = (u64)(64 - count_bits(m));
        off[sq] = next_off;
        next_off += (i64)1 << (64 - (i64)shift[sq]);

        /* 4. every subset of the mask (Carry-Rippler) -> classical attack set */
        sub = U0;
        do {
            att = U0;
            for (d = first_dir; d < 8; d += 2)
                att |= ray_attack(sq, sub, d);
            table[off[sq] + (i64)((sub * magic[sq]) >> shift[sq])] = att;
            sub = (sub - m) & m;
        } while (sub != U0);
    }
}

/* cg_tables.py: the module body. Fills every non-const table. Safe to call twice: every
 * element is assigned, nothing is accumulated across calls. */
void init_tables(void)
{
    i64 p, sq, sg;

    /* :83 KNIGHT_ATT, KING_ATT, PAWN_ATT, RAYS = _build_attacks() */
    build_attacks();

    /* :91-101 magics.npz, rebuilt from the embedded magics (needs RAYS) */
    build_magic(0, R_MAGIC, R_MASK, R_SHIFT, R_OFF, R_TABLE);
    build_magic(1, B_MAGIC, B_MASK, B_SHIFT, B_OFF, B_TABLE);

    /* :111-117 CASTLE_MASK */
    for (sq = 0; sq < 64; sq++)
        CASTLE_MASK[sq] = 15;
    CASTLE_MASK[0] = 13;    /* a1 rook */
    CASTLE_MASK[7] = 14;    /* h1 rook */
    CASTLE_MASK[4] = 12;    /* e1 king */
    CASTLE_MASK[56] = 7;    /* a8 rook */
    CASTLE_MASK[63] = 11;   /* h8 rook */
    CASTLE_MASK[60] = 3;    /* e8 king */

    /* :252-263 MG_TABLE, EG_TABLE.
     * QUIRK: the Python comment above this loop says "white reads sq^56". It is stale: the code
     * indexes WHITE directly and flips BLACK, and the code is what is ported. */
    for (p = 0; p < 6; p++) {
        for (sq = 0; sq < 64; sq++) {
            MG_TABLE[IX_PSQ(p, sq)] = MG_VALUE[p] + MG_PST[p][sq];
            EG_TABLE[IX_PSQ(p, sq)] = EG_VALUE[p] + EG_PST[p][sq];
            MG_TABLE[IX_PSQ(p + 6, sq)] = MG_VALUE[p] + MG_PST[p][sq ^ 56];
            EG_TABLE[IX_PSQ(p + 6, sq)] = EG_VALUE[p] + EG_PST[p][sq ^ 56];
        }
    }

    /* :268-274 MG_SIGNED, EG_SIGNED: white adds, black subtracts */
    for (p = 0; p < 12; p++) {
        sg = p < 6 ? 1 : -1;
        for (sq = 0; sq < 64; sq++) {
            MG_SIGNED[IX_PSQ(p, sq)] = sg * (i64)MG_TABLE[IX_PSQ(p, sq)];
            EG_SIGNED[IX_PSQ(p, sq)] = sg * (i64)EG_TABLE[IX_PSQ(p, sq)];
        }
    }
}

